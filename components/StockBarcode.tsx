export default function StockBarcode({ itemId, variantId, sku, quantity }: {
  itemId: string;
  variantId?: string;
  sku: string;
  quantity: number;
}) {
  if (quantity <= 0) return null;
  const url = `/api/stock/${encodeURIComponent(itemId)}/barcode${variantId ? `?variantId=${encodeURIComponent(variantId)}` : ""}`;
  return (
    <a href={`${url}${variantId ? "&" : "?"}print=1`} target="_blank" rel="noopener noreferrer"
      title={`Print barcode labels for ${sku}`} aria-label={`Print barcode labels for ${sku}`}
      style={{ display: "block", marginTop: 6, width: 160, maxWidth: "100%", color: "var(--blue)", fontSize: 10 }}>
      {/* SVG is generated by the authenticated stock barcode endpoint. */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img src={url} alt={`Barcode ${sku}`} loading="lazy" style={{ display: "block", width: "100%", height: 48, objectFit: "contain", background: "white" }} />
      Print labels
    </a>
  );
}
